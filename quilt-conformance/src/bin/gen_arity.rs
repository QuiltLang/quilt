//! Regenerate `quilt/src/langs/arity.rs` from the vendored tree-sitter grammars.
//!
//! Run via `bin/gen-arity`. `bin/check-arity` runs the same thing and fails if
//! the working tree changed, so a grammar bump that adds, drops or renames a
//! repeat container shows up as a reviewable diff in the PR rather than as a
//! silent change in where emit (`←`) is allowed to splice.
//!
//! See `quilt-conformance/src/arity.rs` for what "variadic" is derived from and
//! why; issue #202 for the decision to derive it at all.

use miette::{IntoDiagnostic as _, Result, WrapErr as _};
use quilt_conformance::{arity, repo_root};
use std::fmt::Write as _;
use std::process::Command;

/// The `#[cfg]` a language's table is gated on, matching `quilt/src/langs/mod.rs`.
///
/// Rust's is the one that is not just its own feature: `bootstrap` re-exports
/// `RustLanguage` unchanged, so its table has to survive `--no-default-features
/// --features bootstrap` too.
fn cfg_for(name: &str) -> String {
    if name == "rust" {
        r#"#[cfg(any(feature = "rust", feature = "bootstrap"))]"#.to_string()
    } else {
        format!(r#"#[cfg(feature = "{name}")]"#)
    }
}

fn main() -> Result<()> {
    let tables = arity::derive_all()?;
    let path = repo_root().join("quilt/src/langs/arity.rs");

    let mut out = String::new();
    out.push_str(HEADER);
    for (name, tags) in &tables {
        let n = tags.len();
        writeln!(
            out,
            "\n/// {name}: {n} node kind(s) the grammar gives a variable number of direct children.",
        )
        .unwrap();
        writeln!(out, "{}", cfg_for(name)).unwrap();
        writeln!(out, "pub static {}: &[&str] = &[", name.to_uppercase()).unwrap();
        for tag in tags {
            writeln!(out, "    {tag:?},").unwrap();
        }
        out.push_str("];\n");
    }

    std::fs::write(&path, &out)
        .into_diagnostic()
        .wrap_err_with(|| format!("writing {}", path.display()))?;

    // The tables are one entry per line, which rustfmt would otherwise pack;
    // formatting here keeps `bin/fmt-check` and `bin/check-arity` from
    // disagreeing about the same file.
    let status = Command::new("rustfmt")
        .args(["--edition", "2021"])
        .arg(&path)
        .status()
        .into_diagnostic()
        .wrap_err("running rustfmt")?;
    if !status.success() {
        return Err(miette::miette!("rustfmt failed on {}", path.display()));
    }

    println!("wrote {}", path.display());
    for (name, tags) in &tables {
        println!("  {name}: {} variadic", tags.len());
    }
    Ok(())
}

const HEADER: &str = r#"//! Which node kinds are variadic containers, derived from the tree-sitter
//! grammars vendored under `quilt/grammars/`.
//!
//! @generated by `bin/gen-arity` — do not edit by hand. `bin/check-arity`
//! regenerates this file and fails if it differs, so the tables cannot drift
//! from the grammars the parsers were built from.
//!
//! Each table is the set of node kinds whose grammar rule gives them a variable
//! number of *direct* children, sorted so [`Arity::from_table`] can binary
//! search it. `quilt-conformance/src/arity.rs` documents the derivation — in
//! short: a `REPEAT` in the rule body, following hidden rules (tree-sitter
//! inlines them) but not category rules, aliases or tokens (each of those is one
//! node, so its repeats are its own children, not its parent's).
//!
//! These tables used to be hand-written per language, which is how bash and zsh
//! came to classify eleven shared constructs differently (#150) and how a
//! renamed node kind could silently stop being treated as a container (#174).
//! Deriving them is issue #202.
//!
//! [`Arity::from_table`]: crate::lang::Arity::from_table
"#;
