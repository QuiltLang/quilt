// The browser build is `--target web`, whose default export is the wasm init()
// that callers `await`. Node's build instantiates on require, so this is a
// no-op — it exists so a program written for the playground (`import init from
// "quilt"; await init()`) also runs under `quilt run`.
export default async function init() {
  return RT;
}

