// Turn a wasm-pack build of quilt-wasm into the package (issue #306).
//
//   node quilt-wasm/js/assemble.mjs <out-dir> <nodejs|web>
//
// Run by bin/build-wasm, after `wasm-pack build --out-name quilt_wasm_raw`.
// The runtime is plain JavaScript (runtime.js) and the wasm only its edges, so
// wasm-pack's module is not the package entry. This writes, next to it:
//
//   quilt_runtime.js  runtime.js, as CommonJS for --target nodejs
//   quilt_wasm.js     the entry: the runtime, bound to quilt_wasm_raw.js
//   quilt_wasm.d.ts   its types
//
// and points package.json at them. The entry keeps the name wasm-pack used to
// give the bindings, so `pkg/quilt_wasm.js` is still what everything loads.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const [out, target] = process.argv.slice(2);
if (!out || !["nodejs", "web"].includes(target)) {
  console.error("usage: assemble.mjs <out-dir> <nodejs|web>");
  process.exit(2);
}

const runtime = readFileSync(join(here, "runtime.js"), "utf8");
// runtime.js ends in a single `export { … };`, which is all CommonJS needs
// changed.
const EXPORTS = /^export \{([^}]*)\};\s*$/m;
if (!EXPORTS.test(runtime)) throw new Error("runtime.js must end in one `export { … };`");

const BANNER = "// Generated by quilt-wasm/js/assemble.mjs. Do not edit.\n";

let entry;
if (target === "nodejs") {
  writeFileSync(
    join(out, "quilt_runtime.js"),
    `"use strict";\n${runtime.replace(EXPORTS, "module.exports = {$1};")}`,
  );
  entry = `${BANNER}"use strict";
const raw = require("./quilt_wasm_raw.js");
const runtime = require("./quilt_runtime.js");
runtime.__bindWasm(raw);
module.exports = { ...runtime, __memoryBytes: raw.__memoryBytes };
`;
} else {
  writeFileSync(join(out, "quilt_runtime.js"), runtime);
  // The wasm-bindgen functions only work after init(), but binding the module
  // namespace now is fine: nothing calls into it before then.
  entry = `${BANNER}import * as raw from "./quilt_wasm_raw.js";
import { __bindWasm } from "./quilt_runtime.js";
__bindWasm(raw);
export * from "./quilt_runtime.js";
export { default, initSync, __memoryBytes } from "./quilt_wasm_raw.js";
`;
}
writeFileSync(join(out, "quilt_wasm.js"), entry);
let types = readFileSync(join(here, "quilt_wasm.d.ts"), "utf8");
if (target === "web") {
  types += `
/** Load the wasm. Await it before calling the runtime. */
export { default, initSync } from "./quilt_wasm_raw.js";
`;
}
writeFileSync(join(out, "quilt_wasm.d.ts"), types);

const manifest = join(out, "package.json");
const pkg = JSON.parse(readFileSync(manifest, "utf8"));
pkg.main = "quilt_wasm.js";
pkg.types = "quilt_wasm.d.ts";
if (pkg.module) pkg.module = "quilt_wasm.js";
const files = new Set([...(pkg.files ?? []), "quilt_wasm.js", "quilt_wasm.d.ts", "quilt_runtime.js"]);
pkg.files = [...files].sort();
writeFileSync(manifest, `${JSON.stringify(pkg, null, 2)}\n`);
